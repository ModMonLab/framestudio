/**
 * Onboarding (FR-ONB-01): a first-run dialog (theme, voice worker check or skip, template or empty) and a short guided
 * tour (8 steps) over the workspace: modes, Layers, assets, the builder, lines and takes, the timeline, export and the
 * command palette. Both can be reopened from Help.
 */
import { useEffect, useLayoutEffect, useState } from 'react';
import { Button, Dialog, Segmented, StatusBadge, useTheme, type ThemeChoice, t as tt } from '@frame/ui';
import { api, type WorkerStatus } from '../lib/api.js';
import { setPrefs, shortcutLabel, usePrefs } from '../lib/prefs.js';

export function FirstRun({ templates, onTemplate }: { templates: { value: string; label: string }[]; onTemplate: (ref: string) => void }) {
  const prefs = usePrefs();
  const { theme, setTheme } = useTheme();
  const [step, setStep] = useState(0);
  const [worker, setWorker] = useState<WorkerStatus | 'checking'>();
  if (prefs.onboarded) return null;
  const done = (template?: string) => {
    setPrefs({ onboarded: true });
    if (template) onTemplate(template);
    requestAnimationFrame(() => document.querySelector<HTMLInputElement>('[aria-label="Folder"]')?.focus());
  };
  const check = () => {
    setWorker('checking');
    api.worker().then(setWorker).catch(() => setWorker({ state: 'offline', message: 'The server could not be reached' }));
  };
  const steps = [
    { title: 'Welcome to Frame', body: <>
      <p>{tt('Frame makes 2D animated episodes: build characters, give them voices, direct scenes and export video. Let\'s set up three things.')}</p>
      <Segmented label={tt('Theme')} value={theme} onChange={(v) => setTheme(v as ThemeChoice)} options={[{ value: 'dark', label: 'Dark' }, { value: 'light', label: 'Light' }, { value: 'system', label: 'System' }]} />
    </> },
    { title: 'Voice worker', body: <>
      <p>{tt('Voices are generated by the Voice Worker, a separate program on a machine with a GPU. You can skip this and connect it later in Settings; recordings and everything else work without it.')}</p>
      <div className="st-settings-row">
        <Button onClick={check} loading={worker === 'checking'}>{tt('Check connection')}</Button>
        {worker && worker !== 'checking' && <StatusBadge tone={worker.state === 'connected' || worker.state === 'busy' ? 'success' : 'warning'}>{worker.state === 'connected' || worker.state === 'busy' ? `Connected${worker.label ? ` · ${worker.label}` : ''}` : worker.state === 'misconfigured' ? 'Not set up' : 'Offline'}</StatusBadge>}
      </div>
      {worker && worker !== 'checking' && worker.state !== 'connected' && worker.state !== 'busy' && <p className="fr-hint">{worker.hint ?? worker.message}  {tt('Set its address in Settings ▸ Voice worker.')}</p>}
    </> },
    { title: 'Start a project', body: <>
      <p>{tt('Start from a template (a ready scene with cast slots, shots and sound) or from an empty project.')}</p>
      <ul className="st-onb-templates">
        <li><Button onClick={() => done()}>{tt('Empty project')}</Button></li>
        {templates.slice(0, 8).map((t) => <li key={t.value}><Button variant="ghost" onClick={() => done(t.value)}>{t.label}</Button></li>)}
      </ul>
    </> },
  ];
  const s = steps[step]!;
  return (
    <Dialog title={s.title} open onClose={() => done()} footer={<>
      <span className="fr-faint">{tt('Step')} {step + 1}  {tt('of')} {steps.length}</span>
      <span className="fr-spacer" />
      {step > 0 && <Button onClick={() => setStep(step - 1)}>{tt('Back')}</Button>}
      {step < steps.length - 1 ? <Button variant="primary" onClick={() => setStep(step + 1)}>{step === 1 && !worker ? 'Skip' : 'Next'}</Button> : <Button onClick={() => done()}>{tt('Skip')}</Button>}
    </>}>
      <div className="st-form st-form--flush">{s.body}</div>
    </Dialog>
  );
}

interface TourStep { target: string; title: string; body: string }
const TOUR: TourStep[] = [
  { target: '[aria-label="Workspace mode"]', title: 'Stage, Direct and Edit', body: 'Stage arranges the scene, Direct adds performance and shots, Edit is timeline-first. Keys 1, 2 and 3 switch.' },
  { target: 'aside[aria-label="Layers"]', title: 'Layers', body: 'Everything in the scene by depth plane. Click to select; the canvas, timeline and properties follow.' },
  { target: '[aria-label="Panels"]', title: 'Assets', body: 'Characters, sets, props, expressions, actions, effects, text and sound. Drag onto the canvas or timeline.' },
  { target: 'aside[aria-label="Properties"]', title: 'Properties and the builder', body: 'Settings for the selection. For a character, “Edit character” opens the builder: parts, looks and colours in both styles.' },
  { target: '[aria-label="Properties tabs"]', title: 'Lines and takes', body: 'A character’s Audio tab adds lines and makes takes: generate, upload or record. Scene ▸ Script view shows every line.' },
  { target: 'section[aria-label="Timeline"]', title: 'Timeline', body: 'Shots, dialogue, acting, face and sound per character. Drag to move, edges to trim, S to split.' },
  { target: '[data-tour="export"]', title: 'Export', body: 'Export to video, GIF or image sequence. The Problems badge beside it lists anything that blocks export, with fixes.' },
  { target: '[aria-label="Workspace mode"]', title: 'Find anything', body: `Press ${shortcutLabel('palette')} to search commands, scenes, layers, assets, settings and help.` },
];

export function Tour() {
  const prefs = usePrefs();
  const [step, setStep] = useState(0);
  const [rect, setRect] = useState<DOMRect>();
  const s = TOUR[step]!;
  useLayoutEffect(() => {
    if (prefs.tourDone) return;
    const el = document.querySelector(s.target);
    setRect(el?.getBoundingClientRect());
  }, [step, prefs.tourDone, s.target]);
  useEffect(() => {
    if (prefs.tourDone) return;
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && setPrefs({ tourDone: true });
    addEventListener('keydown', onKey);
    return () => removeEventListener('keydown', onKey);
  }, [prefs.tourDone]);
  if (prefs.tourDone) return null;
  const finish = () => setPrefs({ tourDone: true });
  const below = !rect || rect.bottom + 180 < innerHeight;
  const left = rect ? Math.max(12, Math.min(innerWidth - 332, rect.left)) : innerWidth / 2 - 160;
  const top = rect ? (below ? rect.bottom + 10 : Math.max(12, rect.top - 170)) : innerHeight / 2 - 80;
  return (
    <div className="st-tour" role="dialog" aria-modal="false" aria-labelledby="st-tour-title">
      {rect && <div className="st-tour-ring" style={{ left: rect.left - 4, top: rect.top - 4, width: rect.width + 8, height: rect.height + 8 }} aria-hidden />}
      <div className="st-tour-card" style={{ left, top }}>
        <div className="fr-faint">{tt('Tour ·')} {step + 1}  {tt('of')} {TOUR.length}</div>
        <h2 id="st-tour-title">{s.title}</h2>
        <p>{s.body}</p>
        <div className="st-settings-row">
          <Button variant="ghost" onClick={finish}>{tt('Skip tour')}</Button>
          <span className="fr-spacer" />
          {step > 0 && <Button onClick={() => setStep(step - 1)}>{tt('Back')}</Button>}
          {step < TOUR.length - 1 ? <Button variant="primary" autoFocus onClick={() => setStep(step + 1)}>{tt('Next')}</Button> : <Button variant="primary" onClick={finish}>{tt('Done')}</Button>}
        </div>
      </div>
    </div>
  );
}
