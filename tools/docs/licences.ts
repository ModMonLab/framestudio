/**
 * Licence report (NFR-17, `pnpm docs:licences`): every JavaScript dependency, the bundled fonts, the bundled content
 * and the Voice Worker's models and libraries, with each licence checked against the distribution allowlist.
 * Writes docs/licences.md and docs/licences.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Licences compatible with distributing Frame and with commercial use of its output. */
export const ALLOWED: Record<string, string> = {
  MIT: 'permissive',
  ISC: 'permissive',
  'BSD-2-Clause': 'permissive',
  'BSD-3-Clause': 'permissive',
  'Apache-2.0': 'permissive (keep NOTICE files)',
  '0BSD': 'permissive',
  'BlueOak-1.0.0': 'permissive',
  Zlib: 'permissive',
  '(MIT AND Zlib)': 'permissive',
  'Python-2.0': 'permissive',
  'CC-BY-4.0': 'data with attribution (browser-support tables, build time only)',
  'MPL-2.0': 'file-level copyleft: unmodified files, source available from the package',
  'OFL-1.1': 'fonts: may be bundled; not sold on their own',
  'LicenseRef-Frame-Bundled': 'Frame bundled content: free to use in exported videos, including commercially',
};

export interface Pkg { name: string; version: string; license: string }

/** The installed JavaScript packages and their declared licences, from pnpm. */
export function jsPackages(): Pkg[] {
  const raw = JSON.parse(execSync('pnpm licenses list --json', { cwd: repo, encoding: 'utf8', maxBuffer: 64 << 20 })) as Record<string, { name: string; versions: string[] }[]>;
  const out: Pkg[] = [];
  for (const [license, list] of Object.entries(raw)) for (const p of list) for (const v of p.versions) out.push({ name: p.name, version: v, license });
  return out.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function contentLicences(): Record<string, { count: number; redistributable: boolean; commercialUse: boolean }> {
  const out: Record<string, { count: number; redistributable: boolean; commercialUse: boolean }> = {};
  const root = path.join(repo, 'content/assets');
  for (const kind of fs.readdirSync(root)) for (const f of fs.readdirSync(path.join(root, kind))) {
    if (!f.endsWith('.json')) continue;
    const l = (JSON.parse(fs.readFileSync(path.join(root, kind, f), 'utf8')) as { license?: { id: string; redistributable: boolean; commercialUse: boolean } }).license;
    const id = l?.id ?? 'missing';
    const e = (out[id] ??= { count: 0, redistributable: true, commercialUse: true });
    e.count++;
    e.redistributable &&= !!l?.redistributable;
    e.commercialUse &&= !!l?.commercialUse;
  }
  return out;
}

function fonts(): { family: string; license: string; file: string }[] {
  const f = JSON.parse(fs.readFileSync(path.join(repo, 'content/fonts/fonts.json'), 'utf8')) as { license: Record<string, string> };
  return Object.entries(f.license).map(([family, text]) => ({ family, license: text.split(' ')[0]!, file: /\((licenses\/[^)]+)\)/.exec(text)?.[1] ?? '' }));
}

/** Platform builds of native packages (esbuild, rollup) differ per OS; they are checked but not listed. */
const PLATFORM = /[-/](linux|darwin|win32|freebsd|android|sunos|openbsd)(-|$)/;

export function licenceReport(all: Pkg[] = jsPackages()) {
  const pkgs = all.filter((p) => !PLATFORM.test(p.name));
  const content = contentLicences();
  const fontList = fonts();
  const problems = [
    ...all.filter((p) => !ALLOWED[p.license]).map((p) => `${p.name}@${p.version}: ${p.license} is not on the allowlist`),
    ...fontList.filter((f) => !ALLOWED[f.license] || !fs.existsSync(path.join(repo, 'content/fonts', f.file))).map((f) => `font ${f.family}: ${f.license} without a licence file`),
    ...Object.entries(content).filter(([id, e]) => !ALLOWED[id] || !e.redistributable || !e.commercialUse).map(([id]) => `content licence ${id} is not redistributable for commercial use`),
  ];
  const byLicence: Record<string, number> = {};
  for (const p of pkgs) byLicence[p.license] = (byLicence[p.license] ?? 0) + 1;
  const json = { packages: pkgs, fonts: fontList, content, worker: 'services/voice-worker/LICENSES.md', problems };
  const md = [
    '# Licence report (NFR-17)',
    '',
    'Generated by `pnpm docs:licences` — do not edit. Checked by tools/test/licences.test.ts.',
    '',
    problems.length ? `**${problems.length} problem(s):**\n\n${problems.map((p) => `- ${p}`).join('\n')}` : '**No problems:** every licence below is on the distribution allowlist.',
    '',
    '## Allowlist',
    '',
    '| Licence | Why it is allowed |',
    '|---|---|',
    ...Object.entries(ALLOWED).map(([k, v]) => `| ${k} | ${v} |`),
    '',
    '## Bundled content',
    '',
    '| Licence | Assets | Redistributable | Commercial use |',
    '|---|---|---|---|',
    ...Object.entries(content).map(([id, e]) => `| ${id} | ${e.count} | ${e.redistributable ? 'yes' : 'no'} | ${e.commercialUse ? 'yes' : 'no'} |`),
    '',
    'All bundled characters, parts, props, sets, sounds and music are original to Frame (provenance in each manifest).',
    '',
    '## Fonts',
    '',
    '| Family | Licence | Licence text |',
    '|---|---|---|',
    ...fontList.map((f) => `| ${f.family} | ${f.license} | content/fonts/${f.file} |`),
    '',
    '## Voice Worker',
    '',
    'Models and Python libraries: [services/voice-worker/LICENSES.md](../services/voice-worker/LICENSES.md). Models are downloaded only after the owner accepts their licences (`fetch-models --accept-licences`).',
    '',
    '## ffmpeg',
    '',
    'Not bundled. Downloaded on first use (decision 0013): a pinned, hash-checked LGPL/GPL build kept in the user profile with its licence notice; Frame calls it as a separate program.',
    '',
    `## JavaScript packages (${pkgs.length})`,
    '',
    'Platform-specific binary builds (for example `@esbuild/<os>-<cpu>`) are checked but not listed; they carry their parent package\'s licence.',
    '',
    Object.entries(byLicence).sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k}: ${n}`).join(' · '),
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
    ...pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
  ].join('\n');
  return { json, md };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { json, md } = licenceReport();
  fs.writeFileSync(path.join(repo, 'docs/licences.md'), md);
  fs.writeFileSync(path.join(repo, 'docs/licences.json'), `${JSON.stringify(json, null, 2)}\n`);
  console.log(`${json.packages.length} packages, ${json.problems.length} problems → docs/licences.md`);
}
